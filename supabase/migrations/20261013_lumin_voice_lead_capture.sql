-- Consent-aware write-only bridge from the Lumin voice worker to the live SD Dialer schema.
-- Lead origin is stored as the allowed "website" value; the specific source is kept in custom_fields/timeline metadata.

create schema if not exists lumin_voice_private;
revoke all on schema lumin_voice_private from public, anon, authenticated;
grant usage on schema lumin_voice_private to anon;

create table if not exists lumin_voice_private.api_keys (
  id bigint generated by default as identity primary key,
  key_hash bytea not null unique,
  company_id uuid not null references public.companies(id) on delete cascade,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists lumin_voice_private.lead_calls (
  company_id uuid not null references public.companies(id) on delete cascade,
  call_id text not null check (pg_catalog.char_length(call_id) between 1 and 128),
  lead_id uuid not null references public.leads(id) on delete cascade,
  consent_at timestamptz not null,
  created_at timestamptz not null default now(),
  primary key (company_id, call_id)
);

alter table lumin_voice_private.api_keys enable row level security;
alter table lumin_voice_private.lead_calls enable row level security;
revoke all on table lumin_voice_private.api_keys from public, anon, authenticated;
revoke all on table lumin_voice_private.lead_calls from public, anon, authenticated;

create or replace function lumin_voice_private.normalize_phone(p_phone text)
returns text
language plpgsql
immutable
parallel safe
set search_path = ''
as $fn$
declare
  v_digits text;
begin
  v_digits := pg_catalog.regexp_replace(coalesce(p_phone, ''), '[^0-9]', '', 'g');
  if pg_catalog.left(v_digits, 5) = '00351' and pg_catalog.char_length(v_digits) = 14 then
    return pg_catalog.substr(v_digits, 6);
  end if;
  if pg_catalog.left(v_digits, 3) = '351' and pg_catalog.char_length(v_digits) = 12 then
    return pg_catalog.substr(v_digits, 4);
  end if;
  return v_digits;
end;
$fn$;

revoke all on function lumin_voice_private.normalize_phone(text) from public, anon, authenticated;

create or replace function lumin_voice_private.register_lead(
  p_api_key text,
  p_call_id text,
  p_name text,
  p_phone text,
  p_consent_to_contact boolean,
  p_consent_at timestamptz
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $fn$
declare
  v_company_id uuid;
  v_call_id text;
  v_name text;
  v_phone text;
  v_phone_key text;
  v_lead_id uuid;
  v_created boolean := false;
  v_timeline_description text := 'Ligação telefónica com o agente Lumin; consentimento para contacto de seguimento confirmado.';
begin
  if p_api_key is null
     or pg_catalog.char_length(p_api_key) not between 32 and 512
     or p_call_id is null
     or pg_catalog.char_length(pg_catalog.btrim(p_call_id)) not between 1 and 128 then
    raise exception 'invalid lead capture request' using errcode = '22023';
  end if;

  if p_consent_to_contact is distinct from true
     or p_consent_at is null
     or p_consent_at > pg_catalog.statement_timestamp() + interval '5 minutes' then
    raise exception 'valid contact consent is required' using errcode = '42501';
  end if;

  v_call_id := pg_catalog.btrim(p_call_id);
  v_name := pg_catalog.regexp_replace(pg_catalog.btrim(coalesce(p_name, '')), '[[:space:]]+', ' ', 'g');
  v_phone := pg_catalog.btrim(coalesce(p_phone, ''));

  if pg_catalog.char_length(v_name) not between 2 and 120 then
    raise exception 'a contact name is required' using errcode = '22023';
  end if;

  select k.company_id
    into v_company_id
    from lumin_voice_private.api_keys as k
   where k.is_active = true
     and k.key_hash = extensions.digest(pg_catalog.convert_to(p_api_key, 'UTF8'), 'sha256')
   limit 1;

  if v_company_id is null
     or not exists (
       select 1
         from public.companies as c
        where c.id = v_company_id
          and c.status = 'active'
     ) then
    raise exception 'invalid lead capture credentials' using errcode = '42501';
  end if;

  v_phone_key := lumin_voice_private.normalize_phone(v_phone);
  if v_phone_key !~ '^[0-9]{9,15}$' then
    raise exception 'invalid phone number' using errcode = '22023';
  end if;

  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended('voice-call:' || v_company_id::text || ':' || v_call_id, 0)
  );
  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended('voice-phone:' || v_company_id::text || ':' || v_phone_key, 0)
  );

  select c.lead_id
    into v_lead_id
    from lumin_voice_private.lead_calls as c
   where c.company_id = v_company_id
     and c.call_id = v_call_id;

  if v_lead_id is not null then
    return pg_catalog.jsonb_build_object(
      'lead_id', v_lead_id,
      'created', false,
      'replayed', true
    );
  end if;

  select l.id
    into v_lead_id
    from public.leads as l
   where l.company_id = v_company_id
     and lumin_voice_private.normalize_phone(l.telefone) = v_phone_key
   order by l.created_at desc
   limit 1
   for update;

  if v_lead_id is null then
    insert into public.leads (
      company_id,
      nome,
      telefone,
      origem,
      consentimento_rgpd,
      data_consentimento,
      custom_fields,
      skip_auto_assign
    )
    values (
      v_company_id,
      v_name,
      v_phone,
      'website',
      true,
      p_consent_at,
      pg_catalog.jsonb_build_object(
        'lumin_voice_agent',
        pg_catalog.jsonb_build_object(
          'source', 'lumin_voice_agent',
          'call_id', v_call_id,
          'consent_at', p_consent_at
        )
      ),
      false
    )
    returning id into v_lead_id;

    v_created := true;
  else
    update public.leads
       set consentimento_rgpd = true,
           data_consentimento = p_consent_at,
           custom_fields = coalesce(custom_fields, '{}'::jsonb) ||
             pg_catalog.jsonb_build_object(
               'lumin_voice_agent',
               pg_catalog.jsonb_build_object(
                 'source', 'lumin_voice_agent',
                 'call_id', v_call_id,
                 'consent_at', p_consent_at
               )
             )
     where id = v_lead_id;
  end if;

  insert into public.lead_timeline (
    company_id,
    lead_id,
    tipo,
    descricao,
    usuario_id,
    metadata
  )
  values (
    v_company_id,
    v_lead_id,
    'chamada',
    v_timeline_description,
    null,
    pg_catalog.jsonb_build_object(
      'source', 'lumin_voice_agent',
      'call_id', v_call_id,
      'consent_to_contact', true,
      'consent_at', p_consent_at
    )
  );

  insert into lumin_voice_private.lead_calls (company_id, call_id, lead_id, consent_at)
  values (v_company_id, v_call_id, v_lead_id, p_consent_at);

  return pg_catalog.jsonb_build_object(
    'lead_id', v_lead_id,
    'created', v_created,
    'replayed', false
  );
end;
$fn$;


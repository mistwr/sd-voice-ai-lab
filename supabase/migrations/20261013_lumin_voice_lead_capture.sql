-- Consent-aware write-only bridge from the Lumin voice worker to SD Dialer.
-- This project uses public.leads / public.lead_actividades and profiles-based ownership.
create schema if not exists private;

create table if not exists private.lumin_voice_api_keys (
  id bigint generated by default as identity primary key,
  key_hash bytea not null unique,
  owner_id uuid not null references public.profiles(id) on delete cascade,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists private.lumin_voice_lead_calls (
  call_id text primary key check (length(call_id) between 1 and 128),
  lead_id uuid not null references public.leads(id) on delete cascade,
  consent_at timestamptz not null,
  created_at timestamptz not null default now()
);

alter table private.lumin_voice_api_keys enable row level security;
alter table private.lumin_voice_lead_calls enable row level security;
revoke all on table private.lumin_voice_api_keys from public, anon, authenticated;
revoke all on table private.lumin_voice_lead_calls from public, anon, authenticated;
grant usage on schema private to anon;

create or replace function private.lumin_voice_normalize_phone(p_phone text)
returns text
language plpgsql
immutable
parallel safe
set search_path = ''
as $fn$
declare
  v_digits text;
begin
  v_digits := pg_catalog.regexp_replace(coalesce(p_phone, ''), '[^0-9]', '', 'g');
  if pg_catalog.left(v_digits, 5) = '00351' and pg_catalog.length(v_digits) = 14 then
    return pg_catalog.substr(v_digits, 6);
  end if;
  if pg_catalog.left(v_digits, 3) = '351' and pg_catalog.length(v_digits) = 12 then
    return pg_catalog.substr(v_digits, 4);
  end if;
  return v_digits;
end;
$fn$;

revoke all on function private.lumin_voice_normalize_phone(text) from public, anon, authenticated;

create or replace function private.lumin_voice_register_lead(
  p_api_key text,
  p_call_id text,
  p_name text,
  p_phone text,
  p_consent_to_contact boolean,
  p_consent_at timestamptz
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $fn$
declare
  v_owner_id uuid;
  v_phone_key text;
  v_lead_id uuid;
  v_created boolean := false;
begin
  if p_api_key is null or p_call_id is null or pg_catalog.length(pg_catalog.btrim(p_call_id)) not between 1 and 128 then
    raise exception 'invalid lead capture request' using errcode = '22023';
  end if;
  if p_consent_to_contact is distinct from true or p_consent_at is null then
    raise exception 'contact consent is required' using errcode = '42501';
  end if;
  if p_name is null or pg_catalog.length(pg_catalog.btrim(p_name)) not between 2 and 120 then
    raise exception 'a contact name is required' using errcode = '22023';
  end if;

  select k.owner_id
    into v_owner_id
    from private.lumin_voice_api_keys as k
   where k.is_active = true
     and k.key_hash = extensions.digest(pg_catalog.convert_to(p_api_key, 'UTF8'), 'sha256')
   limit 1;

  if v_owner_id is null then
    raise exception 'invalid lead capture credentials' using errcode = '42501';
  end if;

  if not exists (
    select 1
      from public.profiles as p
     where p.id = v_owner_id
       and p.active = true
       and p.company_name = 'Soluções Diferentes'
       and (p.role = 'admin' or p.is_superadmin = true)
  ) then
    raise exception 'lead capture owner is not configured' using errcode = '42501';
  end if;

  v_phone_key := private.lumin_voice_normalize_phone(p_phone);
  if v_phone_key !~ '^[0-9]{9,15}$' then
    raise exception 'invalid phone number' using errcode = '22023';
  end if;

  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended('call:' || pg_catalog.btrim(p_call_id), 0));
  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended('lead:' || v_owner_id::text || ':' || v_phone_key, 0));

  select c.lead_id
    into v_lead_id
    from private.lumin_voice_lead_calls as c
   where c.call_id = pg_catalog.btrim(p_call_id);

  if v_lead_id is not null then
    return pg_catalog.jsonb_build_object('lead_id', v_lead_id, 'created', false, 'replayed', true);
  end if;

  select l.id
    into v_lead_id
    from public.leads as l
   where (l.user_id = v_owner_id or l.uploaded_by = v_owner_id)
     and private.lumin_voice_normalize_phone(l.telefone) = v_phone_key
   order by l.created_at desc
   limit 1
   for update;

  if v_lead_id is null then
    insert into public.leads (
      nome,
      telefone,
      origem,
      user_id,
      uploaded_by,
      data_contacto,
      score,
      score_demografico,
      score_comportamental,
      score_engagement
    )
    values (
      pg_catalog.btrim(p_name),
      pg_catalog.btrim(p_phone),
      'lumin_voice_agent',
      v_owner_id,
      v_owner_id,
      p_consent_at,
      15,
      20,
      0,
      0
    )
    returning id into v_lead_id;

    v_created := true;
    insert into public.lead_actividades (lead_id, tipo, descricao, user_id)
    values (
      v_lead_id,
      'criacao',
      'Lead criada após chamada telefónica do agente Lumin; acompanhamento autorizado.',
      v_owner_id
    );
  else
    insert into public.lead_actividades (lead_id, tipo, descricao, user_id)
    values (
      v_lead_id,
      'atualizacao',
      'Contacto após chamada telefónica do agente Lumin; acompanhamento autorizado.',
      v_owner_id
    );
  end if;

  insert into private.lumin_voice_lead_calls (call_id, lead_id, consent_at)
  values (pg_catalog.btrim(p_call_id), v_lead_id, p_consent_at);

  return pg_catalog.jsonb_build_object('lead_id', v_lead_id, 'created', v_created, 'replayed', false);
end;
$fn$;

